  /* ---------------- 自动切句 ----------------
     为什么不在数据里手工切：
       一篇文章几十句，手切既费时又容易把一句话切断。这里按标点
       自动切，再「过短的合并、过长的按逗号拆」，一篇课文进来就
       直接变成关卡池，以后加文章只写自然段就行。
     切完每条 8~30 字：太短打一个照面就结束，太长一关打不完。 */
  function cutSents(text) {
    var parts = [], buf = '';
    for (var i = 0; i < text.length; i++) {
      var c = text.charAt(i);
      if (c === '\n' || c === '\r') { if (buf) { parts.push(buf); buf = ''; } continue; }
      buf += c;
      if ('。！？；'.indexOf(c) >= 0) { parts.push(buf); buf = ''; }
    }
    if (buf) parts.push(buf);
    return parts.map(function (s) { return s.trim(); }).filter(function (s) { return s.length > 0; });
  }
  /* 超长句在中点附近找逗号劈开，递归到都不超长为止 */
  function splitLong(s, max) {
    if (s.length <= max) return [s];
    var mid = Math.floor(s.length / 2), cut = -1;
    for (var d = 0; d < s.length; d++) {
      var a = mid - d, b = mid + d;
      if (a > 3 && '，、：'.indexOf(s.charAt(a)) >= 0) { cut = a; break; }
      if (b < s.length - 3 && '，、：'.indexOf(s.charAt(b)) >= 0) { cut = b; break; }
    }
    if (cut < 0) return [s];
    return splitLong(s.slice(0, cut + 1), max).concat(splitLong(s.slice(cut + 1), max));
  }
  function buildLines(paras) {
    var raw = [];
    (paras || []).forEach(function (p) {
      cutSents(p).forEach(function (s) {
        splitLong(s, 30).forEach(function (x) { raw.push(x); });
      });
    });
    var out = [];
    for (var i = 0; i < raw.length; i++) {
      var s = raw[i];
      /* 太短的往下一句并，但并完不超过 26 字 —— 不然一关要打半天 */
      while (s.length < 9 && i + 1 < raw.length && s.length + raw[i + 1].length <= 26) {
        s += raw[++i];
      }
      out.push(s);
    }
    return out;
  }

